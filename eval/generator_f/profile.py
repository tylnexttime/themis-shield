SYSTEM = ("You write institutional deployment profiles for a synthetic evaluation set of a privacy gate. "
          "Everything you write is invented and institutional (never about an individual person). "
          "You answer with exactly one JSON object and nothing else: no prose, no code fence.")

TASK = """Write `profile.json` for ONE invented organisation: a **regional public health and community-care network**
(hospitals, community health centres, aged-care services, mental-health services) in an Australian regional setting.
Follow this schema exactly (all keys present, JSON types as stated):

{schema}

Shapes and rules:
- `organisation`: an invented network name that does not resemble any real health service, hospital group or company.
  `organisation_forms`: at least three other written forms (a short name / acronym of two to five capital letters, a
  "The ..." form, a lower-case plain-text form). The acronym is the organisation's **own short form**.
- `description`: one paragraph. No person is named anywhere in the profile; use role titles only.
- `business_identifier`: {{"scheme": "ABN", "value": "dd ddd ddd ddd", "forms": [the value as written with spaces, and
  the same 11 digits without spaces]}}. Invent a checksum-valid ABN (ABR mod-89 rule); it must not be a real business's.
- `email_domain`: a reserved domain ending in `.example` (for example `<something>.example`).
- `sites`: at least 14 objects {{"name": ..., "forms": [written variants], "address": "street address of the facility",
  "reception": "(0x) 5550 xxxx"}}: hospitals, community health centres, aged-care residences, mental-health services.
  Facility names are invented. Towns may be real regional Australian towns, but no facility name may be a real one.
  Each site's `name` is also a place where staff and patients live (see `site_note`, which says so).
- `buildings`: at least 14 building / wing / ward / clinic-room names (strings).
- `role_mailboxes`: at least 10 role addresses on `email_domain` (enquiries@, privacy@, servicedesk@, ...).
- `main_lines`: at least 3 strings; `reception_numbers`: at least 10 distinct strings. **Phones only from the fiction
  ranges**: `(0x) 5550 xxxx` or `(0x) 7010 xxxx` with x a real area code digit (02, 03, 07, 08), or `1300 975 707` to
  `1300 975 711`, or `1800 975 707` to `1800 975 711`. Plain strings, not objects.
- `role_titles`: at least 35 job/role titles (clinical, allied health, aged care, mental health, administration,
  IT, facilities, governance), used without names.
- `programmes`: at least 14 objects {{"code": ..., "title": ...}} (clinical programmes, community services, training
  modules); `research_projects`: at least 6 objects {{"code": ..., "title": ...}}.
- `committees`: at least 10 committee / staff-network / advisory-group names (include some whose names contain words
  like health, disability, faith, pride, union, Aboriginal, so that look-alikes exist); `initiatives`: at least 14
  initiatives, campaigns and events (for example awareness weeks); `committee_note`: one line saying these are
  institutional names, not statements about people.
- `code_formats`: at least 5 entries; `reference_number_formats`: at least 13 entries. **Pattern notation: `#` is one
  digit, `@` is one capital letter, every other character is literal** (for example `INC-######`, `WO-@@-####`). Name
  the entries after what they are. The reference formats MUST include entries with exactly these keys: ticket_number,
  case_number, reference_number, order_number, invoice_number, asset_id, cost_centre, form_number, provider_number,
  client_account, software_version, build_number, payroll_group. Make the formats varied and realistic; several
  should be digit runs of 5 to 8 digits, because they imitate personal identifiers.
- `public_dates`: at least 10 objects {{"event": ..., "date": "D Month YYYY"}} in 2026-2027: public holidays,
  awareness days, the organisation's open days and annual general meeting.
- `personal_identifier_formats_issued`: at least four formats of identifiers the organisation issues to PEOPLE
  (staff number, patient / client unit-record number, volunteer number, student-placement number), in the same
  pattern notation, **each carrying the organisation's own short form as a literal prefix** (the acronym from
  `organisation_forms`, in capitals, for example `<ACRONYM>-S######`). They are personal, so they are never
  institutional values.
- `site_note`: say that a site's bare name is also a suburb or town where people live.
- `_about`: one line: what this file is.

Return the JSON object only."""


def build_params() -> dict:
    schema = (ROOT / "inputs" / "profile-schema.md").read_text(encoding="utf-8")
    return {"model": AUTHOR_MODEL, "max_tokens": 32000, "thinking": {"type": "adaptive"},
            "output_config": {"effort": "high"}, "system": SYSTEM,
            "messages": [{"role": "user", "content": TASK.format(schema=schema)}]}


def extract_json(text: str) -> dict:
    t = text.strip()
    if t.startswith("```"):
        t = re.sub(r"^```[a-zA-Z]*\n|\n```$", "", t)
    a, b = t.find("{"), t.rfind("}")
    return json.loads(t[a:b + 1])


def sanitise(p: dict) -> dict:
    fixes = {"abn": 0, "abn_forms": 0, "phones": 0, "email_domain": 0, "mailboxes": 0}
    vals = sv.Values(20261111 + 7)
    bi = p.get("business_identifier") or {}
    digits = re.sub(r"\D", "", str(bi.get("value", "")))
    if not (sv.abn_valid(digits) and V.abn_ok(digits)) or digits in V.REAL_ABNS:
        bi["value"] = vals.abn()
        fixes["abn"] = 1
        digits = re.sub(r"\D", "", bi["value"])
    forms = [str(f) for f in bi.get("forms", [])]
    want = [f"{digits[:2]} {digits[2:5]} {digits[5:8]} {digits[8:]}", digits]
    if not forms or any(re.sub(r"\D", "", f) != digits for f in forms):
        bi["forms"] = want
        fixes["abn_forms"] = 1
    bi["value"] = want[0] if fixes["abn"] else bi.get("value", want[0])
    bi["scheme"] = "ABN"
    p["business_identifier"] = bi
    for key in ("main_lines", "reception_numbers"):
        out = []
        for ph in p.get(key, []):
            ph = ph if isinstance(ph, str) else str(ph.get("number", ""))
            if not V.phone_ok(ph):
                ph = vals.business_phone()
                fixes["phones"] += 1
            out.append(ph)
        p[key] = out
    dom = str(p.get("email_domain", ""))
    if not dom.endswith(".example"):
        slug = re.sub(r"[^a-z0-9]+", "", str(p.get("organisation", "network")).lower())[:20] or "network"
        dom = f"{slug}.example"
        p["email_domain"] = dom
        fixes["email_domain"] = 1
    mb = []
    for m in p.get("role_mailboxes", []):
        m = str(m)
        d = V.email_domain_of(m)
        if d is None or not V.domain_reserved(d):
            m = m.split("@")[0] + "@" + dom
            fixes["mailboxes"] += 1
        mb.append(m)
    p["role_mailboxes"] = mb
    return fixes


def main() -> int:
    if (ROOT / "profile.json").exists():
        print("profile.json exists; not calling the API again")
        return 0
    params = build_params()
    total = ledger_total()
    if total + 2.0 > BUDGET_USD:
        print("STOP: ledger total plus estimate over the cap")
        return 4
    (ROOT / "requests" / "profile.request.json").write_text(
        json.dumps({"endpoint": "messages.stream", "base_url": "https://api.anthropic.com", **params},
                   ensure_ascii=False, indent=1), encoding="utf-8")
    c = client()
    with c.messages.stream(**params) as stream:
        msg = stream.get_final_message()
    usage = sum_usage([{k: getattr(msg.usage, k, 0) or 0 for k in
                        ("input_tokens", "output_tokens", "cache_creation_input_tokens", "cache_read_input_tokens")}])
    usage["note"] = f"{msg.id}, 1 succeeded, 0 errored (streamed Messages call, stop_reason {msg.stop_reason})"
    (ROOT / "requests" / "profile.usage.json").write_text(json.dumps(usage), encoding="utf-8")
    book("f-profile", AUTHOR_MODEL, "high",
         "split F profile: one invented regional public health network (profile.json)",
         ROOT / "requests" / "profile.usage.json", batch=False)
    text = "".join(b.text for b in msg.content if getattr(b, "type", "") == "text")
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "profile.raw.txt").write_text(text, encoding="utf-8")
    print(f"profile call: stop_reason={msg.stop_reason} output_tokens={usage['output_tokens']} chars={len(text)}")
    try:
        prof = extract_json(text)
    except json.JSONDecodeError as exc:
        print(f"STOP: profile output is not JSON ({exc.msg} at {exc.pos})")
        return 6
    fixes = sanitise(prof)
    rep = V.Report()
    V.check_profile(prof, rep)
    pats, bad = load_patterns()
    hits = scan_case(prof, pats)
    forms = prof.get("personal_identifier_formats_issued", {})
    short = [f for f in prof.get("organisation_forms", []) if re.fullmatch(r"[A-Z]{2,6}", str(f))]
    prefixed = [k for k, pat in forms.items() if any(str(pat).startswith(s) for s in short)]
    info = {"fixes": fixes, "validator_failures": len(rep.failures), "validator_codes": sorted(rep.codes()),
            "denylist_hits": hits, "issued_formats": len(forms), "issued_formats_with_org_prefix": len(prefixed),
            "sites": len(prof.get("sites", [])), "role_titles": len(prof.get("role_titles", [])),
            "reference_formats": len(prof.get("reference_number_formats", {}))}
    log_round("profile", info)
    print(json.dumps(info))
    if rep.failures or hits or len(prefixed) < 3:
        (ROOT / "profile.rejected.json").write_text(json.dumps(prof, ensure_ascii=False, indent=1), encoding="utf-8")
        print("STOP: profile does not meet the rules; saved as profile.rejected.json")
        return 7
    (ROOT / "profile.json").write_text(json.dumps(prof, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("profile.json written")
    return 0


if __name__ == "__main__":
    sys.exit(main())