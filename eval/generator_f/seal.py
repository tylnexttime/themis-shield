"""Step 8: seal. cases.jsonl -> sealed/half-o.jsonl + sha256, profile beside it, prep_profiles, manifest, PROVENANCE.

    python seal.py check     build cases.jsonl, run validator + denylist + extra quotas (no sealing)
    python seal.py seal      all of the above, then seal
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from collections import Counter

import common as C
import finalize as F
from store import load_state

ROOT = C.ROOT


def counts(cases: list[dict], profile: dict) -> dict:
    labels = Counter(s["label"] for c in cases for s in c["spans"])
    prof = [c for c in cases if c["organisation"] == profile["organisation"]]
    inj = [c for c in cases if c.get("injection")]
    return {
        "cases": len(cases), "clean_documents": sum(1 for c in cases if not c["spans"]),
        "gold_spans": sum(labels.values()), "hard_negatives": sum(len(c["hard_negatives"]) for c in cases),
        "by_label": dict(sorted(labels.items())), "by_genre": dict(sorted(Counter(c["genre"] for c in cases).items())),
        "by_organisation_kind": {"profiled": len(prof), "other_workplace": len(cases) - len(prof),
                                 "other_workplaces_distinct": len({c["organisation"] for c in cases} - {profile["organisation"]})},
        "by_injection_position": dict(Counter(c["injection"]["position"] for c in inj)),
        "injected_cases": len(inj), "injected_cases_without_pi": sum(1 for c in inj if not c["spans"]),
        "hard_to_spot_cases": sum(1 for c in cases if c.get("hard_to_spot")),
        "long_documents": sum(1 for c in cases if 9000 <= len(c["text"]) <= 24000),
        "sensitive_spans": {"total": sum(1 for c in cases for s in c["spans"] if "indirect" in s),
                            "indirect": sum(1 for c in cases for s in c["spans"] if s.get("indirect")),
                            "negative": sum(1 for c in cases for s in c["spans"] if s.get("negative"))},
        "characters_total": sum(len(c["text"]) for c in cases),
    }


def build_and_check() -> tuple[list[dict], bool, str]:
    import hashlib
    cases = F.valid_cases()
    path = ROOT / "cases.jsonl"
    man = ROOT / "manifest.json"
    new_text = "".join(C.jline(c) + chr(10) for c in cases)
    sha = hashlib.sha256(new_text.encode("utf-8")).hexdigest()
    if man.exists() and sha in man.read_text(encoding="utf-8"):
        pass  # rebuilt file is identical to the sealed one: leave cases.jsonl and manifest.json untouched
    else:
        F.write_cases(path, cases)
        if man.exists():
            man.unlink()  # a stale manifest would fail the validator's MANIFEST rule; it is rewritten at seal time
    rc, text = F.run_validator(path)
    rc2, dtext = F.run_denylist(path)
    rc3 = subprocess.run([C.PY, str(ROOT / "extra_quotas.py"), str(path)], capture_output=True, text=True,
                         encoding="utf-8")
    out = text + "\n\n" + dtext + "\n\n" + rc3.stdout.strip()
    (ROOT / "rounds").mkdir(exist_ok=True)
    (ROOT / "rounds" / "last_check.txt").write_text(out, encoding="utf-8")
    return cases, rc == 0 and rc2 == 0 and rc3.returncode == 0, out


def provenance(c: dict, man: dict) -> str:
    return f"""# PROVENANCE: split F, half O (free-prose set)

Counts, hashes and names only; no case, value or profile content is quoted in this file.

## Who made what

| artefact | made by | model / effort | from |
|---|---|---|---|
| `profile.json` | one streamed Messages call (`profile.py`), ABN / phones / domain checked and, if invalid, regenerated by code (fixes needed: {man['profile_fixes']}) | claude-opus-5-5, effort high, adaptive thinking, max_tokens 32000 | `inputs/profile-schema.md` and the task text |
| `plan.jsonl` ({c['cases_planned']} specifications) | `plan.py`, deterministic, seed {man['seeds']['plan']} | none (code); checksum values by `safevalues.py` (own code, cross-checked against the validator) | `inputs/brief.md` quotas |
| the documents | Batch API, one request per plan entry (`author.py`) | claude-opus-5-5, effort high, adaptive thinking, max_tokens 64000, cached system prompt (brief + taxonomy + profile) | `inputs/brief.md`, `inputs/taxonomy.md`, `profile.json`, the case specification |
| offsets, `case_level`, `organisation`, flags | `markup.py` / `validate.py` (code); never a model | none | the inline markup |
| repair of rule failures and pointer flags | one repair batch | claude-opus-5-5, effort high | the author's own previous output and the rule codes |
| real-world pointer check | Batch API, one request per case | claude-sonnet-5-5, effort high | the plain text only |
| blind labelling | Batch API, one request per case | claude-sonnet-5-5, effort xhigh, max_tokens 64000, system = taxonomy only | the plain text only |
| review round | Batch API, one request per case with a disagreement | claude-opus-5-5, effort high | text, gold and labeller version; the author decides, a script applies |
| validation | `validator/check_cases.py` (split-E copy, protocol constants only), `validator/denylist_check.py`, `extra_quotas.py` | code | `cases.jsonl` |

## Files read by the orchestrator

`taxonomy.md`, `format.md`, `profile-schema.md`, `brief.md` (split E author inputs, copied to `inputs/`),
`split-e/validator/check_cases.py` and `VALIDATOR.md`, `split-e/prep_profiles.py`, `tools/origin-denylist.txt`
(loaded in code only, never printed or copied), `themis-shield/eval/convert_profile.py` (imported by
`prep_profiles.py`), and the ledger tool's price table (two rows: the models used). Nothing else of the repository
was read: no gate code, prompts or detectors, no other split's cases or generators. No web access.

## Counts

- cases: {c['cases']} (planned {c['cases_planned']}; dropped by rule {man['dropped_total']})
- clean documents: {c['clean_documents']}; gold spans: {c['gold_spans']}; hard negatives: {c['hard_negatives']}
- organisation: profiled {c['by_organisation_kind']['profiled']}, other workplaces {c['by_organisation_kind']['other_workplace']} over {c['by_organisation_kind']['other_workplaces_distinct']} labels
- injected cases: {c['injected_cases']} (positions {c['by_injection_position']}); hard-to-spot: {c['hard_to_spot_cases']}; long documents: {c['long_documents']}
- sensitive spans: {c['sensitive_spans']}
- sha256 cases: `{man['sha256']['cases']}`; plan: `{man['sha256']['plan']}`; profile: `{man['sha256']['profile']}`

## Notes

- Every earlier split came from a template generator; split F is per-document prose by a single model family at one
  effort, so document style is more uniform across cases than the number of cases suggests.
- The workplace `organisation` field of non-profiled cases carries the plan's label (workplace number and sector); the
  invented workplace's own name appears only in the prose.
- Rounds (counts) are in `rounds/`; spend is in the ledger (`f-profile`, `f-pilot`, `f-author-1`, `f-pointer-1`,
  `f-repair-1`, optional `f-topup-1` / `f-pointer-2`, `f-label-1`, `f-review-1`, `f-count-tokens`).
"""


def seal() -> int:
    cases, ok, out = build_and_check()
    print(out)
    if not ok:
        print("NOT SEALING: a check failed")
        return 1
    profile = json.loads((ROOT / "profile.json").read_text(encoding="utf-8"))
    (ROOT / "sealed").mkdir(exist_ok=True)
    sealed = ROOT / "sealed" / "half-o.jsonl"
    shutil.copyfile(ROOT / "cases.jsonl", sealed)
    h = C.sha256_file(sealed)
    (ROOT / "sealed" / "half-o.sha256").write_text(f"{h}  half-o.jsonl\n", encoding="utf-8", newline="\n")
    shutil.copyfile(ROOT / "profile.json", ROOT / "sealed" / "profile.json")
    print(subprocess.run([C.PY, str(ROOT / "prep_profiles.py"), "o"], capture_output=True, text=True,
                         encoding="utf-8").stdout.strip())
    st = load_state()
    rounds = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in (ROOT / "rounds").glob("*.json")}
    c = counts(cases, profile)
    plan_n = len(C.read_jsonl(ROOT / "plan.jsonl")) + len(C.read_jsonl(ROOT / "plan.topup.jsonl"))
    c["cases_planned"] = plan_n
    man = {
        "split": "test-f", "half": "O", "generator": "O", "id_prefix": "FO-", "counts": c,
        "seeds": {"plan": 20261111, "safe_values": 20261112},
        "models": {"profile": {"model": C.AUTHOR_MODEL, "effort": "high", "thinking": "adaptive", "max_tokens": 32000},
                   "author": {"model": C.AUTHOR_MODEL, "effort": "high", "thinking": "adaptive", "max_tokens": 64000},
                   "repair": {"model": C.AUTHOR_MODEL, "effort": "high"},
                   "pointer_check": {"model": C.CHECK_MODEL, "effort": "high"},
                   "blind_labeller": {"model": C.CHECK_MODEL, "effort": "xhigh", "max_tokens": 64000},
                   "review": {"model": C.AUTHOR_MODEL, "effort": "high"}},
        "sha256": {"cases": h, "plan": C.sha256_file(ROOT / "plan.jsonl"), "profile": C.sha256_file(ROOT / "profile.json"),
                   "taxonomy": C.sha256_file(ROOT / "inputs" / "taxonomy.md"),
                   "brief": C.sha256_file(ROOT / "inputs" / "brief.md"),
                   "validator": C.sha256_file(ROOT / "validator" / "check_cases.py"),
                   "institution_profile": C.sha256_file(ROOT / "profiles" / "institution" / "test-f-o.json"),
                   "context": C.sha256_file(ROOT / "profiles" / "context-o.txt"),
                   "agreement_md": C.sha256_file(ROOT / "AGREEMENT.md")},
        "profile_fixes": rounds.get("profile", {}).get("fixes"),
        "dropped_total": sum(1 for r in st.values() if r["status"] == "dropped"),
        "status_totals": dict(Counter(r["status"] for r in st.values())),
        "rounds": {k: v for k, v in rounds.items() if k.startswith(("ingest", "review", "agreement"))},
    }
    (ROOT / "manifest.json").write_text(json.dumps(man, indent=1, ensure_ascii=False), encoding="utf-8")
    (ROOT / "PROVENANCE.md").write_text(provenance(c, man), encoding="utf-8", newline="\n")
    rc, text = F.run_validator(ROOT / "cases.jsonl")  # now with manifest.json next to it (MANIFEST rule)
    print("validator with manifest:", "PASS" if rc == 0 else "FAIL")
    print("sealed sha256", h)
    return 0


if __name__ == "__main__":
    sys.exit(seal() if sys.argv[1] == "seal" else (print(build_and_check()[2]) or 0))