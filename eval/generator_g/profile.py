def extract_json(text: str) -> dict:
    t = text.strip()
    if t.startswith("```"):
        t = re.sub(r"^```[a-zA-Z]*\n|\n```$", "", t)
    a, b = t.find("{"), t.rfind("}")
    return json.loads(t[a:b + 1])


def sanitise(p: dict, seed: int) -> dict:
    fixes = {"abn": 0, "abn_forms": 0, "phones": 0, "email_domain": 0, "mailboxes": 0}
    vals = sv.Values(seed + 7)
    bi = p.get("business_identifier") or {}
    digits = re.sub(r"\D", "", str(bi.get("value", "")))
    if not (sv.abn_valid(digits) and V.abn_ok(digits)) or digits in V.REAL_ABNS:
        bi["value"] = vals.abn()
        fixes["abn"] = 1
        digits = re.sub(r"\D", "", bi["value"])
    forms = [str(f) for f in bi.get("forms", [])]
    want = [f"{digits[:2]} {digits[2:5]} {digits[5:8]} {digits[8:]}", digits]
    if not forms or any(re.sub(r"\D", "", f) != digits for f in forms):
        bi["forms"] = want
        fixes["abn_forms"] = 1
    bi["value"] = want[0] if fixes["abn"] else bi.get("value", want[0])
    bi["scheme"] = "ABN"
    p["business_identifier"] = bi
    for key in ("main_lines", "reception_numbers"):
        out = []
        for ph in p.get(key, []):
            ph = ph if isinstance(ph, str) else str(ph.get("number", ""))
            if not V.phone_ok(ph):
                ph = vals.business_phone()
                fixes["phones"] += 1
            out.append(ph)
        p[key] = out
    for s in p.get("sites", []):
        if isinstance(s, dict) and s.get("reception") and not V.phone_ok(str(s["reception"])):
            s["reception"] = vals.business_phone()
            fixes["phones"] += 1
    dom = str(p.get("email_domain", ""))
    if not dom.endswith(".example"):
        slug = re.sub(r"[^a-z0-9]+", "", str(p.get("organisation", "org")).lower())[:20] or "org"
        dom = f"{slug}.example"
        p["email_domain"] = dom
        fixes["email_domain"] = 1
    mb = []
    for m in p.get("role_mailboxes", []):
        m = str(m)
        d = V.email_domain_of(m)
        if d is None or not V.domain_reserved(d):
            m = m.split("@")[0] + "@" + dom
            fixes["mailboxes"] += 1
        mb.append(m)
    p["role_mailboxes"] = mb
    return fixes


def evaluate(prof: dict, seed: int) -> tuple[dict, dict, list[str]]:
    fixes = sanitise(prof, seed)
    rep = V.Report()
    V.check_profile(prof, rep)
    pats, _bad = load_patterns()
    hits = scan_case(prof, pats)
    forms = prof.get("personal_identifier_formats_issued", {})
    short = [f for f in prof.get("organisation_forms", []) if re.fullmatch(r"[A-Z]{2,6}", str(f))]
    prefixed = [k for k, pat in forms.items() if any(str(pat).startswith(s) for s in short)]
    keys = set((prof.get("reference_number_formats") or {}))
    need = {"ticket_number", "case_number", "reference_number", "order_number", "invoice_number", "asset_id", "cost_centre",
            "form_number", "provider_number", "client_account", "software_version", "build_number", "payroll_group"}
    problems = []
    if rep.failures:
        problems += [f"[{c}] {d}" for c, _cid, d in rep.failures[:6]]
    if hits:
        problems.append(f"[DENYLIST] {hits} forbidden-term hit(s): invent names that resemble nothing real")
    if len(prefixed) < 3:
        problems.append("[PREFIX] personal_identifier_formats_issued needs at least three formats that start with the "
                        "organisation's own short form (an acronym of 2-6 capitals from organisation_forms)")
    if not need <= keys:
        problems.append("[KEYS] reference_number_formats must include " + ", ".join(sorted(need - keys)))
    info = {"fixes": fixes, "validator_failures": len(rep.failures), "validator_codes": sorted(rep.codes()),
            "denylist_hits": hits, "issued_formats": len(forms), "issued_formats_with_org_prefix": len(prefixed),
            "sites": len(prof.get("sites", [])), "role_titles": len(prof.get("role_titles", [])),
            "reference_formats": len(prof.get("reference_number_formats", {})),
            "organisation_abn_regenerated_by_code": bool(fixes["abn"])}
    return info, fixes, problems


def run(h: C.Half) -> int:
    if h.profile_path.exists():
        print(f"{h.L}: profile.json exists; not calling the API again")
        return 0
    seed = C.HALVES[h.L]["seed"]
    schema = (C.ROOT / "inputs" / "profile-schema.md").read_text(encoding="utf-8")
    task = (TASK.replace("@ORG@", h.cfg["org_kind"]).replace("@FLAVOUR@", FLAVOUR[h.L]).replace("@SCHEMA@", schema))
    msgs = [{"role": "system", "content": SYSTEM}, {"role": "user", "content": task}]
    tries = []
    for attempt in (1, 2):
        cid = "profile" if attempt == 1 else "profile-retry"
        jobs = [{"case_id": cid, "messages": msgs, "max_tokens": 16000}]
        res, stop = runner.run_calls(h, "author", "profile", jobs)
        if stop:
            print("STOP:", stop)
            return 4
        r = res.get(cid)
        if not r or not r.get("ok") or r.get("finish_reason") == "length":
            tries.append({"attempt": attempt, "result": "no usable output"})
            problems = ["the previous reply was empty or cut off: reply with the complete JSON object only"]
        else:
            try:
                prof = extract_json(r["content"])
            except (json.JSONDecodeError, ValueError) as exc:
                tries.append({"attempt": attempt, "result": f"not JSON ({type(exc).__name__})"})
                problems = ["[JSON] the previous reply was not one valid JSON object: reply with the JSON object only"]
            else:
                info, fixes, problems = evaluate(prof, seed)
                info["attempt"] = attempt
                tries.append(info)
                if not problems:
                    h.profile_path.write_text(json.dumps(prof, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
                    h.round_log("profile", {"tries": tries})
                    print(h.L, "profile.json written", json.dumps(info))
                    return 0
                (h.dir / f"profile.rejected-{attempt}.json").write_text(json.dumps(prof, ensure_ascii=False, indent=1), encoding="utf-8")
        msgs = msgs[:2] + [{"role": "assistant", "content": (r or {}).get("content", "")[:20000]},
                           {"role": "user", "content": "Rule failures to fix (return the complete corrected JSON object only):\n- "
                            + "\n- ".join(problems)}]
    h.round_log("profile", {"tries": tries})
    print(h.L, "STOP: profile does not meet the rules after one retry")
    return 7


if __name__ == "__main__":
    sys.exit(run(C.Half(sys.argv[1])))